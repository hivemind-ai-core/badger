//! Path dependencies and `lang.lock`.
//!
//! Dependencies (transitively) are packages on disk named in `[dependencies]`.
//! Each must satisfy its version requirement (a prefix of the dependency's
//! `[package] version`). `lang.lock` beside the root manifest records every
//! dependency's version, path, and a content hash of its manifest and
//! sources; a build verifies them and refuses changed or unlisted
//! dependencies until `lang update` rewrites the lockfile.

use std::path::{Path, PathBuf};

use crate::manifest::Manifest;

#[derive(Debug, Clone)]
pub struct Dep {
    pub name: String,
    pub version: String,
    /// Package directory (holding `lang.toml`).
    pub dir: PathBuf,
    /// Directory of the entry module: the package's module root.
    pub src_root: PathBuf,
    pub entry: PathBuf,
    pub hash: String,
}

const LOCK: &str = "lang.lock";

/// FNV-1a over the manifest and every `.lang` file (sorted relative paths).
fn content_hash(dir: &Path) -> String {
    fn walk(base: &Path, dir: &Path, out: &mut Vec<(String, Vec<u8>)>) {
        let Ok(rd) = std::fs::read_dir(dir) else { return };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                walk(base, &p, out);
            } else if p.extension().is_some_and(|x| x == "lang")
                || p.file_name().is_some_and(|n| n == "lang.toml")
            {
                let rel = p.strip_prefix(base).unwrap_or(&p).to_string_lossy().replace('\\', "/");
                out.push((rel, std::fs::read(&p).unwrap_or_default()));
            }
        }
    }
    let mut files = vec![];
    walk(dir, dir, &mut files);
    files.sort();
    let mut h: u64 = 0xcbf29ce484222325;
    for (name, bytes) in files {
        for b in name.bytes().chain([0u8]).chain(bytes).chain([0u8]) {
            h ^= b as u64;
            h = h.wrapping_mul(0x100000001b3);
        }
    }
    format!("fnv1a64:{h:016x}")
}

/// Resolve the dependency graph of the project at `project`.
pub fn resolve(project: &Path, m: &Manifest) -> Result<Vec<Dep>, String> {
    let mut out: Vec<Dep> = vec![];
    let mut work: Vec<(PathBuf, Manifest)> = vec![(project.to_path_buf(), m.clone())];
    while let Some((dir, man)) = work.pop() {
        for d in &man.dependencies {
            let ddir = dir.join(&d.path);
            let ddir = ddir
                .canonicalize()
                .map_err(|e| format!("dependency `{}`: cannot open {}: {e}", d.name, ddir.display()))?;
            let dm = Manifest::load(&ddir.join("lang.toml"))
                .map_err(|e| format!("dependency `{}`: {e}", d.name))?;
            if dm.name != d.name {
                return Err(format!(
                    "dependency `{}` at {} is the package `{}`",
                    d.name,
                    ddir.display(),
                    dm.name
                ));
            }
            if let Some(req) = &d.version
                && !(dm.version == *req || dm.version.starts_with(&format!("{req}.")))
            {
                return Err(format!("dependency `{}` requires version {req}, found {}", d.name, dm.version));
            }
            if let Some(prev) = out.iter().find(|x| x.name == d.name) {
                if prev.dir != ddir {
                    return Err(format!(
                        "dependency `{}` resolves to two packages: {} and {}",
                        d.name,
                        prev.dir.display(),
                        ddir.display()
                    ));
                }
                continue;
            }
            let entry = ddir.join(&dm.entry);
            let src_root = entry.parent().map(Path::to_path_buf).unwrap_or_else(|| ddir.clone());
            out.push(Dep {
                name: d.name.clone(),
                version: dm.version.clone(),
                hash: content_hash(&ddir),
                dir: ddir.clone(),
                src_root,
                entry,
            });
            work.push((ddir, dm));
        }
    }
    out.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(out)
}

fn lock_text(project: &Path, deps: &[Dep]) -> String {
    let mut s = String::from("# Generated by `lang update`: dependency versions and content hashes.\n");
    for d in deps {
        let rel = pathdiff(&d.dir, project);
        s.push_str(&format!("{} {} {} {}\n", d.name, d.version, rel, d.hash));
    }
    s
}

fn pathdiff(p: &Path, base: &Path) -> String {
    let base = base.canonicalize().unwrap_or_else(|_| base.to_path_buf());
    let (pc, bc): (Vec<_>, Vec<_>) = (p.components().collect(), base.components().collect());
    let common = pc.iter().zip(&bc).take_while(|(a, b)| a == b).count();
    let mut parts: Vec<String> = vec!["..".into(); bc.len() - common];
    parts.extend(pc[common..].iter().map(|c| c.as_os_str().to_string_lossy().to_string()));
    if parts.is_empty() { ".".into() } else { parts.join("/") }
}

/// Resolve and verify against `lang.lock` (writing it when absent).
pub fn verified(project: &Path, m: &Manifest) -> Result<Vec<Dep>, String> {
    let deps = resolve(project, m)?;
    let lock = project.join(LOCK);
    let expected = lock_text(project, &deps);
    match std::fs::read_to_string(&lock) {
        Err(_) => {
            if !deps.is_empty() {
                std::fs::write(&lock, &expected)
                    .map_err(|e| format!("cannot write {}: {e}", lock.display()))?;
            }
        }
        Ok(found) => {
            let entries = |t: &str| -> Vec<String> {
                t.lines()
                    .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
                    .map(str::to_string)
                    .collect()
            };
            let (want, have) = (entries(&expected), entries(&found));
            for w in &want {
                let name = w.split(' ').next().unwrap_or("");
                match have.iter().find(|h| h.split(' ').next() == Some(name)) {
                    None => {
                        return Err(format!("dependency `{name}` is not in lang.lock; run `lang update`"));
                    }
                    Some(h) if h != w => {
                        return Err(format!(
                            "dependency `{name}` changed since lang.lock was written (locked `{h}`, found `{w}`); run `lang update`"
                        ));
                    }
                    _ => {}
                }
            }
            for h in &have {
                let name = h.split(' ').next().unwrap_or("");
                if !want.iter().any(|w| w.split(' ').next() == Some(name)) {
                    return Err(format!(
                        "lang.lock lists `{name}`, which is no longer a dependency; run `lang update`"
                    ));
                }
            }
        }
    }
    Ok(deps)
}

/// Rewrite `lang.lock` from the current dependencies.
pub fn update(project: &Path) -> Result<Vec<Dep>, String> {
    let m = Manifest::load(&project.join("lang.toml"))?;
    let deps = resolve(project, &m)?;
    std::fs::write(project.join(LOCK), lock_text(project, &deps))
        .map_err(|e| format!("cannot write lang.lock: {e}"))?;
    Ok(deps)
}
